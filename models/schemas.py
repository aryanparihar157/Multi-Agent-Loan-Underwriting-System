"""
Data models and shared state schemas for Multi-Agent Loan Underwriting.
Designed strictly around the CSE476 CA2 specification.
"""
from __future__ import annotations

from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class DecisionEnum(str, Enum):
    SANCTION = "SANCTION"
    DECLINE = "DECLINE"
    REFER = "REFER"


class LoanApplication(BaseModel):
    """Raw loan application submitted by applicant."""
    applicant_id: str
    applicant_name: str
    monthly_income: Optional[float] = None
    existing_emis: float = 0.0
    requested_amount: Optional[float] = None
    tenure_months: Optional[int] = None
    purpose: Optional[str] = "Personal / General Loan"


class BureauRecord(BaseModel):
    """Prior credit bureau record stored in memory."""
    applicant_id: str
    cibil_score: int
    past_defaults: int = 0
    active_loans: int = 0
    late_payment_count_last_2yrs: int = 0
    credit_remarks: str = "Standard history"


class AgentTraceEntry(BaseModel):
    """Log entry capturing each specialist agent's contribution to the audit trail."""
    timestamp: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    agent_name: str
    action: str
    tool_used: str
    status: str
    details: Dict[str, Any]


class CounterOfferDetails(BaseModel):
    """Proposals generated by the Counter-Offer Worker when requested amount fails affordability."""
    eligible_for_counter_offer: bool = False
    max_eligible_loan_amount: Optional[float] = None
    max_amount_emi: Optional[float] = None
    extended_tenure_months: Optional[int] = None
    extended_tenure_emi: Optional[float] = None
    recommendation_note: Optional[str] = None


class SharedUnderwritingRecord(BaseModel):
    """
    The shared in-memory blackboard/state object read and written across all agents.
    Carries intermediate results, bureau records, and the final decision.
    """
    application: LoanApplication
    is_valid: bool = False
    validation_errors: List[str] = Field(default_factory=list)
    
    # Financial extraction
    extracted_monthly_income: Optional[float] = None
    extracted_existing_emis: float = 0.0
    extracted_requested_amount: Optional[float] = None
    extracted_tenure_months: Optional[int] = None
    
    # EMI calculation
    annual_interest_rate: float = 10.5
    computed_monthly_emi: Optional[float] = None
    total_payable_amount: Optional[float] = None
    total_interest: Optional[float] = None
    amortization_summary: Optional[Dict[str, Any]] = None
    
    # Credit assessment
    bureau_profile: Optional[BureauRecord] = None
    credit_risk_level: Optional[str] = None
    credit_check_passed: bool = False
    credit_justification: Optional[str] = None
    
    # Affordability verdict
    emi_to_income_ratio: Optional[float] = None
    total_dti_ratio: Optional[float] = None
    affordability_passed: bool = False
    affordability_verdict: Optional[str] = None
    max_allowed_emi: Optional[float] = None
    
    # Counter offer (Group-of-3 add-on)
    counter_offer: Optional[CounterOfferDetails] = None
    
    # Final Underwriting Decision
    decision: Optional[DecisionEnum] = None
    decision_reason: Optional[str] = None
    one_paragraph_justification: Optional[str] = None
    
    # Audit trail
    agent_trace: List[AgentTraceEntry] = Field(default_factory=list)

    def add_trace(self, agent_name: str, action: str, tool_used: str, status: str, details: Dict[str, Any]) -> None:
        """Appends a trace event to the audit log."""
        self.agent_trace.append(
            AgentTraceEntry(
                agent_name=agent_name,
                action=action,
                tool_used=tool_used,
                status=status,
                details=details
            )
        )
